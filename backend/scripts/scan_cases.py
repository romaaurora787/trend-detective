"""Scan candidate demo cases on real NASA POWER data. Writes docs/demo_scan.md."""
import warnings, numpy as np
from pathlib import Path
warnings.filterwarnings("ignore")
from trend_detective import power, stats
from trend_detective.catalogue import BY_ID

CASES = [  # name, var, lat_min, lat_max, lon_min, lon_max
    ("Lincolnshire", "T2M", 52.6, 53.7, -1.0, 0.4),
    ("Lincolnshire", "PRECTOTCORR", 52.6, 53.7, -1.0, 0.4),
    ("Lincolnshire", "GWETROOT", 52.6, 53.7, -1.0, 0.4),
    ("Lincolnshire", "WS2M", 52.6, 53.7, -1.0, 0.4),
    ("Lincolnshire", "FROST_DAYS", 52.6, 53.7, -1.0, 0.4),
    ("Lincolnshire", "ALLSKY_SFC_SW_DWN", 52.6, 53.7, -1.0, 0.4),
    ("London", "AOD_55", 51.2, 51.8, -0.6, 0.4),
    ("Svalbard (Arctic)", "T2M", 77.0, 80.0, 10.0, 20.0),
    ("Svalbard (Arctic)", "FROST_DAYS", 77.0, 80.0, 10.0, 20.0),
    ("Sahel (Niger/Mali)", "PRECTOTCORR", 12.0, 16.0, -5.0, 5.0),
    ("Sahara (Algeria)", "T2M", 25.0, 30.0, 0.0, 5.0),
    ("Amazon (Rondonia)", "GWETROOT", -12.0, -8.0, -66.0, -60.0),
    ("Amazon (Rondonia)", "T2M_MAX", -12.0, -8.0, -66.0, -60.0),
    ("Beijing", "AOD_55", 39.0, 41.0, 115.5, 117.5),
    ("Delhi", "AOD_55", 28.0, 29.5, 76.5, 78.0),
    ("California Central Valley", "GWETROOT", 35.0, 39.0, -122.0, -119.0),
    ("Spain (Iberia)", "GWETROOT", 37.0, 42.0, -7.0, -1.0),
    ("Wash estuary", "TS", 52.7, 53.2, 0.0, 0.6),
]
MAPS = [
    ("England & Wales", "T2M", 50.0, 55.5, -6.0, 2.0),
    ("England & Wales", "GWETROOT", 50.0, 55.5, -6.0, 2.0),
    ("England & Wales", "PRECTOTCORR", 50.0, 55.5, -6.0, 2.0),
    ("Iberia", "GWETROOT", 36.0, 44.0, -10.0, 0.0),
    ("East Africa", "PRECTOTCORR", -5.0, 5.0, 33.0, 43.0),
    ("Sahel", "PRECTOTCORR", 10.0, 20.0, -10.0, 0.0),
    ("Northern Europe", "GWETROOT", 50.0, 60.0, 0.0, 10.0),
]
lines = ["# Demo-case scan (real NASA POWER data, 1981–2025, run 14 Nov 2026)", "",
         "Generated by `backend/scripts/scan_cases.py`. **Candidates only: check each before claiming it.**", "",
         "## Single-area verdicts", "",
         "| Place | Variable | Period | Trend per decade (95% range) | Total change | p (MK-HR / OLS-neff) | Verdict | Years to detect |",
         "|---|---|---|---|---|---|---|---|"]
for name, var, *box in CASES:
    try:
        s, n = power.fetch_area_series(var, *box)
        r = stats.analyse(s.dropna(), units=BY_ID[var]["units"])
        lo, hi = r["sen_ci95_per_decade"]; u = BY_ID[var]["units"]
        ytd = r["years_to_detect"]; ytd = f"{ytd:.0f}" if ytd else "–"
        row = (f"| {name} ({n} cells) | {BY_ID[var]['name']} | {r['start']}–{r['end']} | {r['sen_slope_per_decade']:+.3g} ({lo:+.3g} to {hi:+.3g}) {u} | "
               f"{r['total_change']:+.3g} | {r['mk_hamed_rao']['p']:.2g} / {r['ols_neff']['p']:.2g} | **{r['verdict']['label']}** | {ytd} |")
    except Exception as e:
        row = f"| {name} | {var} | error: {e} |"
    print(row, flush=True); lines.append(row)
lines += ["", "## Maps (each grid cell tested; Benjamini-Hochberg FDR q = 0.10)", "",
          "| Region | Variable | Cells | Significant alone (p<0.05) | Significant after FDR | Rising / falling after FDR |", "|---|---|---|---|---|---|"]
for name, var, *box in MAPS:
    df, cells = power.fetch_region(var, *box)
    sl, ps = [], []
    for c in cells:
        x = df[c["id"]].dropna()
        if len(x) < 36: continue
        a, p = stats.quick_cell_test(x); sl.append(a); ps.append(p)
    sl, ps = np.array(sl), np.array(ps); sig = stats.fdr(ps)
    row = f"| {name} | {BY_ID[var]['name']} | {len(ps)} | {(ps<0.05).sum()} | {sig.sum()} | {(sig&(sl>0)).sum()} / {(sig&(sl<0)).sum()} |"
    print(row, flush=True); lines.append(row)
out = Path(__file__).resolve().parents[2] / "docs" / "demo_scan.md"
out.write_text("\n".join(lines) + "\n"); print(out)
