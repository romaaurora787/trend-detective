"""Run the five 'beyond the trend line' methods on demo places. Writes docs/beyond_scan.md."""
import warnings
from pathlib import Path
warnings.filterwarnings("ignore")
from trend_detective import beyond, power
from trend_detective.catalogue import BY_ID

CASES = [
    ("Lincolnshire", "T2M", (52.6, 53.7, -1.0, 0.4)),
    ("Lincolnshire", "T2M_MAX", (52.6, 53.7, -1.0, 0.4)),
    ("Lincolnshire", "FROST_DAYS", (52.6, 53.7, -1.0, 0.4)),
    ("Lincolnshire", "PRECTOTCORR", (52.6, 53.7, -1.0, 0.4)),
    ("Lincolnshire", "WS2M", (52.6, 53.7, -1.0, 0.4)),
    ("Lincolnshire", "ALLSKY_SFC_SW_DWN", (52.6, 53.7, -1.0, 0.4)),
    ("Beijing", "AOD_55", (39.0, 41.0, 115.5, 117.5)),
    ("Delhi", "AOD_55", (28.0, 29.5, 76.5, 78.0)),
    ("London", "AOD_55", (51.2, 51.8, -0.6, 0.4)),
    ("Svalbard", "T2M", (77.0, 80.0, 10.0, 20.0)),
    ("Sahel", "PRECTOTCORR", (12.0, 16.0, -5.0, 5.0)),
    ("Amazon (Rondonia)", "PRECTOTCORR", (-12.0, -8.0, -66.0, -60.0)),
    ("Amazon (Rondonia)", "T2M_MAX", (-12.0, -8.0, -66.0, -60.0)),
    ("Sahara", "T2M", (25.0, 30.0, 0.0, 5.0)),
]
lines = ["# Beyond the trend line: real-data scan (NASA POWER, run 14 Nov 2026)", "",
         "Generated by `backend/scripts/scan_beyond.py` using `trend_detective/beyond.py`. Candidates only: check before claiming.", ""]
for place, var, box in CASES:
    s, n = power.fetch_area_series(var, *box)
    b = beyond.beyond(s.dropna())
    name = f"{place}: {BY_ID[var]['name']}"
    lines += [f"## {name}",
              f"- **Records:** {b['records']['headline']} (p highs {b['records']['p_highs']:.3f}, p lows {b['records']['p_lows']:.3f})",
              f"- **Emergence:** {b['emergence']['headline']}",
              f"- **Seasons:** {b['seasons']['headline']}",
              f"- **Erratic?** {b['variability']['headline']} (p = {b['variability']['p']:.3f})",
              f"- **Turning point:** {b['turning_point']['headline']} (BIC gain {b['turning_point']['bic_gain']:.1f}; candidate {b['turning_point']['candidate_year']})",
              ""]
    print("\n".join(lines[-7:]), flush=True)
Path(__file__).resolve().parents[2].joinpath("docs", "beyond_scan.md").write_text("\n".join(lines) + "\n")
